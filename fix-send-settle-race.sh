# fix-send-settle-race.sh
#
# FIX: non-Arc sends stay "pending" in History even though they settled
# on-chain (Arc settles fine). Explorer link is already correct (from_chain
# now populated) — this is the remaining half.
#
# ROOT CAUSE (proven in isolation): a race between two fire-and-forget calls the
# send page makes after a transfer confirms. It POSTs /transactions (insert,
# status 'pending') and then settles via PATCH /transactions/:hash. The PATCH
# matches `WHERE arc_tx_hash = :hash`. On non-Arc chains the settle fired
# SYNCHRONOUSLY right after the un-awaited POST, so the UPDATE frequently ran
# BEFORE the insert committed → it matched zero rows (a no-op UPDATE is not an
# error), the row then landed as 'pending', and nothing ever flipped it. Arc
# only worked by accident: its settle is deferred behind
# waitForTransactionReceipt(), which delays it long enough for the insert to win.
#
# FIX (web-only, 1 file): AWAIT the POST insert before firing the settle PATCH,
# so the row is guaranteed to exist on every chain. No API change — the API's
# `arc_tx_hash OR id` match is already correct once ordering is guaranteed.
# Verified in isolation: old order (patch-before-insert) leaves status=pending;
# new order (insert-then-patch) → status=settled.
#
#   EDIT nexum-web/app/(app)/ramp/... no — app/(app)/send/page.tsx
#
# v2 delivery: base64 → temp file → decode → verify (marker) before replace.
# Whole-file replace of send/page.tsx (no partial-apply risk). Idempotent.
# --revert restores the timestamped backup.
#
# Usage:
#   bash fix-send-settle-race.sh          # apply
#   bash fix-send-settle-race.sh --revert # undo
# ============================================================
set -euo pipefail
STAMP="$(date +%Y%m%d-%H%M%S)"

if [ -d "nexum-web" ]; then WEB="nexum-web"
