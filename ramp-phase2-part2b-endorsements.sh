#!/usr/bin/env bash
# ============================================================================
# ramp-phase2-part2-onramp-ui.sh
#
# Bridge.xyz on-ramp — Phase 2, PART 2 (WEB ONLY). Builds on Part 1's API.
#
# Turns the verified /ramp page into the on-ramp UI:
#   • hooks/useRamp.ts            (EDIT) — adds useOnramp(): corridors,
#       virtual-account create/list, and deposit-activity polling. The KYC
#       hook useRamp() is unchanged.
#   • app/(app)/ramp/page.tsx     (EDIT) — the verified branch (was a "coming
#       soon" placeholder) becomes the flow:
#         currency grid (flag cards, all enabled corridors)
#           → "Get deposit details" confirm step (no money moves)
#           → deposit-instructions card (per-currency fields, copy buttons)
#           → deposit → USDC-delivered status tracker (polls /history).
#       not-started / in-progress / rejected KYC branches are untouched.
#
# All requests go through apiFetch, which attaches the session automatically —
# so the flow works from the real page with no manual tokens. USDC lands on
# Base in the user's Circle wallet. No auto-scroll. 0% fee at launch.
#
# Delivery: v2 (per-file quoted-heredoc base64 -> decode -> verify marker +
# non-empty -> place). Idempotent (marker-guarded), timestamped backups,
# --revert. Verified in sandbox before shipping: web tsc --noEmit AND full
# `next build` both pass.
#
# Usage:
#   bash ramp-phase2-part2-onramp-ui.sh           # apply
#   bash ramp-phase2-part2-onramp-ui.sh --revert  # restore from backups
# ============================================================================
set -euo pipefail

find_web_dir() {
  for d in "nexum-web" "afrifx-web" "." "../nexum-web" "../afrifx-web"; do
    if [ -f "$d/package.json" ] && [ -f "$d/hooks/useRamp.ts" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
WEB_DIR="$(find_web_dir || true)"
if [ -z "${WEB_DIR:-}" ]; then
  echo "✗ Could not find the web package (looked for */hooks/useRamp.ts)." >&2
  echo "  Run this from the repo root (~/AfriFX) or the nexum-web directory." >&2
  exit 1
fi
echo "• Web package: $WEB_DIR"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$WEB_DIR/.ramp-phase2-part2-backup"
MARKER_HOOK="export function useOnramp"
MARKER_PAGE="function OnrampFlow"

F_HOOK="hooks/useRamp.ts"
F_PAGE="app/(app)/ramp/page.tsx"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then
    echo "✗ No backup directory at $BACKUP_DIR — nothing to revert." >&2; exit 1
  fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then
    echo "✗ No manifest found in $BACKUP_DIR — nothing to revert." >&2; exit 1
  fi
  echo "• Reverting run: $LATEST"
  while IFS='|' read -r kind rel; do
    [ -z "${kind:-}" ] && continue
    bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
    if [ -f "$bak" ]; then cp -f "$bak" "$WEB_DIR/$rel"; echo "  ↺ restored $rel"
    else echo "  ⚠ missing backup for $rel (left as-is)" >&2; fi
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."
  exit 0
fi

already() { [ -f "$WEB_DIR/$1" ] && grep -qF "$2" "$WEB_DIR/$1"; }
if already "$F_HOOK" "$MARKER_HOOK" && already "$F_PAGE" "$MARKER_PAGE"; then
  echo "✓ Phase 2 Part 2 already applied (markers present). Nothing to do."
  exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then
    echo "✗ [$label] base64 decode failed — aborting, nothing written." >&2; exit 1; fi
  if [ ! -s "$out" ]; then
    echo "✗ [$label] decoded file is empty — aborting." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then
    echo "✗ [$label] marker not found in decoded content — aborting." >&2; exit 1; fi
}

place_edit() {
  local out="$1" rel="$2"
  if [ ! -f "$WEB_DIR/$rel" ]; then echo "✗ Expected existing file missing: $rel" >&2; exit 1; fi
  cp -f "$WEB_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"
  echo "EDIT|$rel" >> "$MANIFEST"
  cp -f "$out" "$WEB_DIR/$rel"
  echo "  ~ updated $rel (backup saved)"
}

