#!/usr/bin/env bash
#
# 15-fix-invoice-redirect-and-number-scroll.sh
# -------------------------------------------------------------------
# Two fixes (WEB / nexum-web):
#
# 1. INVOICE PAY REDIRECT. A payer who opens an invoice link, chooses
#    "Pay with Nexum wallet", and signs in was dropped on /dashboard
#    instead of returning to the invoice. Two root causes:
#      a) Google OAuth does a full-page redirect; Circle's redirectUri is
#         a fixed bare /signin (must match Google Cloud Console), so the
#         ?returnTo= query param is stripped on the round-trip.
#      b) The AuthGuard bounced guarded routes to /signin?next=... but the
#         signin page only read ?returnTo=, so the destination was ignored.
#    Fix: destination now survives via a cookie across OAuth (same channel
#    the auth intent already uses), and the signin page reconciles all
#    three sources — ?returnTo=  >  ?next=  >  cookie  >  /dashboard —
#    resolved once via a useState initializer so the cookie is consumed
#    exactly once. No change needed to the invoice or create-offer callers.
#
# 2. NUMBER INPUT WHEEL SCROLL. Scrolling the mouse wheel over a focused
#    <input type="number"> silently changed its value everywhere (e.g. the
#    amount on Send drifting while you scroll the page). Fixed in two layers:
#      a) the shared <Input> component blurs number inputs on wheel;
#      b) a global, passive document wheel listener (mounted once in
#         Providers) blurs any focused number input the wheel fires on —
#         covering raw <input type="number"> used by swap/bridge/gateway/
#         disbursement that don't use the shared component.
#
# Files replaced: lib/circle.ts, app/(auth)/signin/page.tsx,
#                 components/ui/input.tsx, app/providers.tsx
# Each embedded (base64) and verified byte-identical on write.
# Typechecks clean (npx tsc --noEmit: 0 errors). Backup + --revert. Idempotent.
# -------------------------------------------------------------------
set -euo pipefail

if   [ -f "./tailwind.config.ts" ] && [ -d "./app" ]; then WEB="."
elif [ -d "./nexum-web" ];                             then WEB="./nexum-web"
elif [ -d "./Nexum-main/nexum-web" ];                  then WEB="./Nexum-main/nexum-web"
else echo "ERROR: run from nexum-web or its parent (couldn't find tailwind.config.ts)." >&2; exit 1; fi
cd "$WEB"
echo "==> Working in: $(pwd)"

BACKUP=".fix15-backup"
FILES=("lib/circle.ts" "app/(auth)/signin/page.tsx" "components/ui/input.tsx" "app/providers.tsx")

if [ "${1:-}" = "--revert" ]; then
  latest=$(ls -1dt "$BACKUP"/* 2>/dev/null | head -n1 || true)
  [ -z "$latest" ] && { echo "No backup found."; exit 1; }
  echo "==> Reverting from $latest"
  for f in "${FILES[@]}"; do [ -f "$latest/$f" ] && mkdir -p "$(dirname "$f")" && cp "$latest/$f" "$f" && echo "   restored $f"; done
  echo "==> Revert complete."; exit 0
fi

