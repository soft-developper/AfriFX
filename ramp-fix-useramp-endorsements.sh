    if [ -f "$d/package.json" ] && [ -f "$d/hooks/useRamp.ts" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
WEB_DIR="$(find_web_dir || true)"
if [ -z "${WEB_DIR:-}" ]; then echo "✗ Could not find the web package." >&2; exit 1; fi
echo "• Web package: $WEB_DIR"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$WEB_DIR/.ramp-fix-useramp-backup"
F_HOOK="hooks/useRamp.ts"
MARKER="endorsementFor"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
