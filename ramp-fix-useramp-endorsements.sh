  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  bak="$BACKUP_DIR/${F_HOOK//\//__}.$LATEST.bak"
  if [ -f "$bak" ]; then cp -f "$bak" "$WEB_DIR/$F_HOOK"; echo "  ↺ restored $F_HOOK"; else echo "✗ missing backup" >&2; exit 1; fi
  echo "✓ Revert complete."; exit 0
fi

if [ -f "$WEB_DIR/$F_HOOK" ] && grep -qF "$MARKER" "$WEB_DIR/$F_HOOK"; then
