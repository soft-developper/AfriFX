#!/usr/bin/env bash
# ============================================================================
# ramp-phase3-part1-webhooks.sh
#
# Bridge.xyz on-ramp — Phase 3, PART 1 (API ONLY). Builds on Phase 2.
#
# Adds real-time webhook ingestion so the /ramp deposit tracker updates the
# instant Bridge pushes an event, instead of only on its 15s poll. The poll
# STAYS as ground truth and reconciles anything a webhook misses — this is an
# optimisation layer, it cannot break the working Phase 2 path.
#
# Built strictly from Bridge's official webhook docs + their TypeScript sample
# (apidocs.bridge.xyz/platform/additional-information/webhooks/signature and
# /get-started/introduction/quick-start/setting-up-webhooks):
#   • src/services/bridgexyz/webhooks.ts (NEW) — RSA-SHA256 signature
#       verification against a PER-ENDPOINT public key (no HMAC). ⚠ digest is
#       double-hashed: SHA256(`${t}.${rawBody}`) then RSA-SHA256 verify over
#       that digest — matches Bridge's own samples. 10-min replay guard.
#       Event parsing + virtual_account.activity detail extraction.
#   • migrations/0020_ramp_webhook_events.sql (NEW) — ramp_webhook_events
#       (deduped audit, keyed on Bridge event_id) + ramp_deposit_events (a
#       mirror of VA activity the tracker can read instantly).
#   • src/services/bridgexyz/repository.ts (EDIT) — recordWebhookEvent (dedupe),
#       upsertDepositEvent (collapse on VA+deposit+type), getDepositEvents…
#   • src/routes/transfers.ts (EDIT) — webhookRouter.post('/bridgexyz'): verify
#       against req.rawBody (already captured by express.json({verify}) in
#       index.ts — same mechanism the Flutterwave webhook uses), dedupe, mirror.
#       200 on accept/dupe, 400 on bad/old signature, 503 if key unset.
#
# Webhook URL will be:  https://<your-api-host>/webhooks/bridgexyz
# Needs env BRIDGE_WEBHOOK_PUBLIC_KEY (PEM) — you get it from the webhook
# create/enable response; curl commands are printed at the end.
#
# NOT changed: Phase 0/1/2 endpoints, the poll tracker, P2P, Trade/Swap, the
# existing Flutterwave webhook. No user-visible change until Part 2 wires the
# tracker to the mirror.
#
# SANDBOX NOTE: Bridge fires no real payments webhooks in sandbox, but its
# POST /v0/webhooks/{id}/send delivers a real SIGNED test event — that proves
# verify + dedupe + mirror end to end. Real deposit webhooks = production.
#
# Delivery: v2 (per-file quoted-heredoc base64 -> decode -> verify marker ->
# place). Idempotent, timestamped backups, --revert. Verified in sandbox before
# shipping: API tsc=0, signature verify unit-tested (good passes, tampered/
# stale/wrong-key rejected), migration applies + dedupe + upsert-collapse hold.
#
# Usage:
#   bash ramp-phase3-part1-webhooks.sh           # apply
#   bash ramp-phase3-part1-webhooks.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_api_dir() {
  for d in "nexum-api" "afrifx-api" "." "../nexum-api" "../afrifx-api"; do
    if [ -f "$d/package.json" ] && [ -d "$d/src/services/bridgexyz" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
API_DIR="$(find_api_dir || true)"
if [ -z "${API_DIR:-}" ]; then
  echo "✗ Could not find the API package (*/src/services/bridgexyz)." >&2
  echo "  Run from the repo root (~/AfriFX) or nexum-api." >&2
  exit 1
fi
echo "• API package: $API_DIR"

# Guard: Phase 2 must be present (we edit its repository + rely on its tables).
if ! grep -qF "getVirtualAccountByAccountCurrency" "$API_DIR/src/services/bridgexyz/repository.ts"; then
  echo "✗ Phase 2 not detected in repository.ts. Apply the Phase 2 scripts first." >&2
  exit 1
fi
# Guard: the raw-body capture + webhookRouter this handler depends on.
if ! grep -qF "webhookRouter" "$API_DIR/src/routes/transfers.ts"; then
  echo "✗ webhookRouter not found in routes/transfers.ts — unexpected repo state." >&2
  exit 1
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$API_DIR/.ramp-phase3-part1-backup"
MARKER_WH="verifyWebhookSignature"
MARKER_WH20="ramp_deposit_events"
MARKER_WHREPO="recordWebhookEvent"
MARKER_WHTR="webhookRouter.post('/bridgexyz'"

F_WH="src/services/bridgexyz/webhooks.ts"
F_WH20="migrations/0020_ramp_webhook_events.sql"
F_WHREPO="src/services/bridgexyz/repository.ts"
F_WHTR="src/routes/transfers.ts"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups at $BACKUP_DIR." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest to revert." >&2; exit 1; fi
  echo "• Reverting run: $LATEST"
  while IFS='|' read -r kind rel; do
    [ -z "${kind:-}" ] && continue
    case "$kind" in
      EDIT) bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
            if [ -f "$bak" ]; then cp -f "$bak" "$API_DIR/$rel"; echo "  ↺ restored $rel"
            else echo "  ⚠ missing backup for $rel" >&2; fi ;;
      NEW)  if [ -f "$API_DIR/$rel" ]; then rm -f "$API_DIR/$rel"; echo "  ✗ removed new $rel"; fi ;;
    esac
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."
  exit 0
fi

already() { [ -f "$API_DIR/$1" ] && grep -qF "$2" "$API_DIR/$1"; }
if already "$F_WH" "$MARKER_WH" && already "$F_WH20" "$MARKER_WH20" \
   && already "$F_WHREPO" "$MARKER_WHREPO" && already "$F_WHTR" "$MARKER_WHTR"; then
  echo "✓ Phase 3 Part 1 already applied. Nothing to do."
  exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then echo "✗ [$label] decode failed." >&2; exit 1; fi
  if [ ! -s "$out" ]; then echo "✗ [$label] empty." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then echo "✗ [$label] marker missing." >&2; exit 1; fi
}
place_new() { local out="$1" rel="$2"; mkdir -p "$(dirname "$API_DIR/$rel")"; cp -f "$out" "$API_DIR/$rel"; echo "NEW|$rel" >> "$MANIFEST"; echo "  + wrote $rel (new)"; }
place_edit() { local out="$1" rel="$2"; if [ ! -f "$API_DIR/$rel" ]; then echo "✗ Missing $rel" >&2; exit 1; fi; cp -f "$API_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"; echo "EDIT|$rel" >> "$MANIFEST"; cp -f "$out" "$API_DIR/$rel"; echo "  ~ updated $rel (backup saved)"; }

echo "• Applying Phase 3 Part 1 …"


