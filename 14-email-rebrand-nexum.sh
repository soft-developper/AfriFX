#!/usr/bin/env bash
#
# 14-email-rebrand-nexum.sh
# -------------------------------------------------------------------
# Rebrands every transactional / broadcast / receipt email from AfriFX
# to Nexum, unifies all three old color schemes (Arc blue, gold email,
# gold PDF) to the Indigo+Cyan brand, and rewrites Africa-scoped copy to
# global ("currencies worldwide", "anyone, anywhere", "160+ currencies").
#
# Files replaced (API side, nexum-api):
#   src/services/email/templates.ts          (3 email shells, receipt/audit copy)
#   src/services/email/broadcast-template.ts (admin announcements)
#   src/services/email/receipt-pdf.ts        (PDF receipt wordmark + palette)
#   src/services/email/notifications.ts      (inline payer footer + PDF filenames)
#   src/lib/brand.ts                         (stale support@afrifx.com default)
#   src/jobs/dutyScheduler.ts                (sub-admin duty-reminder email)
#
# Each file is embedded (base64) and verified byte-identical on write.
# Backup written before changes; --revert restores the latest backup.
# Safe to re-run. API-only deploy (Render).
# -------------------------------------------------------------------
set -euo pipefail

if   [ -f "./package.json" ] && [ -d "./src/services/email" ]; then API="."
elif [ -d "./nexum-api" ];                                       then API="./nexum-api"
elif [ -d "./Nexum-main/nexum-api" ];                            then API="./Nexum-main/nexum-api"
else echo "ERROR: run from nexum-api or its parent (couldn't find src/services/email)." >&2; exit 1; fi
cd "$API"
echo "==> Working in: $(pwd)"

BACKUP=".email-rebrand-backup"
FILES=("src/services/email/templates.ts" "src/services/email/broadcast-template.ts" "src/services/email/receipt-pdf.ts" "src/services/email/notifications.ts" "src/lib/brand.ts" "src/jobs/dutyScheduler.ts")

if [ "${1:-}" = "--revert" ]; then
  latest=$(ls -1dt "$BACKUP"/* 2>/dev/null | head -n1 || true)
  [ -z "$latest" ] && { echo "No backup found."; exit 1; }
  echo "==> Reverting from $latest"
  for f in "${FILES[@]}"; do [ -f "$latest/$f" ] && mkdir -p "$(dirname "$f")" && cp "$latest/$f" "$f" && echo "   restored $f"; done
  echo "==> Revert complete."; exit 0
fi

STAMP=$(date +%Y%m%d-%H%M%S); DEST="$BACKUP/$STAMP"; mkdir -p "$DEST"
for f in "${FILES[@]}"; do [ -f "$f" ] && { mkdir -p "$DEST/$(dirname "$f")"; cp "$f" "$DEST/$f"; }; done
echo "==> Backup written to $DEST"

write_file() { # $1 dest path, reads base64 from heredoc on stdin
  local dest="$1"
  mkdir -p "$(dirname "$dest")"
  base64 -d > "$dest"
  echo "   wrote $dest"
}

