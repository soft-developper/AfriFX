#!/usr/bin/env bash
#
# 16-landing-rebrand-global.sh
# -------------------------------------------------------------------
# Updates the public landing page (WEB / nexum-web) to Nexum + global +
# Circle-wallet framing. The theme colors and the rendered logo were
# already handled by scripts 12/13; this is purely the marketing COPY
# that still read AfriFX / Africa-only / MetaMask-first.
#
# Changes:
#   app/page.tsx
#     - meta description: "African FX rates" -> "160+ currencies worldwide"
#     - hero headline: "Move money across Africa" -> "across borders"
#     - hero paragraph: "13 African currencies" -> "160+ currencies worldwide"
#   components/landing/LandingFeatures.tsx
#     - Trade: "13 African currencies" -> "160+ currencies worldwide"
