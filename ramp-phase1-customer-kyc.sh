#!/usr/bin/env bash
# ramp-phase1-customer-kyc.sh
# Phase 1 of Bridge.xyz on/off-ramp: lazy customer + HOSTED KYC (KYC Links /
# Persona — Nexum never touches SSNs or ID images) + the /ramp page + the
# "On/Off-ramp" nav item. Cross-package (API + web). Builds ON Phase 0
# (requires the Phase 0 skeleton already applied/deployed).
#
#   NEW  nexum-api/migrations/0018_ramp_customers.sql
#   NEW  nexum-api/src/services/bridgexyz/customers.ts    (kyc_links create/status/simulate)
#   NEW  nexum-api/src/services/bridgexyz/repository.ts   (ramp_customers table access)
#   EDIT nexum-api/src/routes/ramp.ts                     (+ customer/KYC endpoints; keeps Phase 0)
#   NEW  nexum-web/hooks/useRamp.ts
#   NEW  nexum-web/app/(app)/ramp/page.tsx                (KYC gate UI)
#   EDIT nexum-web/components/layout/Sidebar.tsx          (+ On/Off-ramp item in Exchange group)
#
# After deploy: run `npm run migrate` in nexum-api to create ramp_customers.
# v2 delivery (per-file quoted heredoc + decode-verify). Idempotent, --revert.
set -euo pipefail

if [ -d "nexum-api" ] && [ -d "nexum-web" ]; then ROOT="."
elif [ -d "../nexum-api" ] && [ -d "../nexum-web" ]; then ROOT=".."
else echo "ERROR: run from repo root (~/AfriFX)." >&2; exit 1; fi

API="$ROOT/nexum-api"; WEB="$ROOT/nexum-web"
MIG="$API/migrations/0018_ramp_customers.sql"
CUSTOMERS="$API/src/services/bridgexyz/customers.ts"
REPO="$API/src/services/bridgexyz/repository.ts"
RAMP="$API/src/routes/ramp.ts"
USERAMP="$WEB/hooks/useRamp.ts"
PAGE="$WEB/app/(app)/ramp/page.tsx"
SIDEBAR="$WEB/components/layout/Sidebar.tsx"

# Phase 0 must be present.
if [ ! -f "$RAMP" ] || [ ! -d "$API/src/services/bridgexyz" ]; then
  echo "ERROR: Phase 0 not found (no ramp.ts / bridgexyz service). Apply ramp-phase0-bridge-skeleton.sh first." >&2
  exit 1
fi
[ -f "$SIDEBAR" ] || { echo "ERROR: $SIDEBAR not found." >&2; exit 1; }

TS=$(date +%Y%m%d-%H%M%S)
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

if [ "${1:-}" = "--revert" ]; then
  rm -f "$MIG" "$CUSTOMERS" "$REPO" "$USERAMP" "$PAGE"
  rmdir "$WEB/app/(app)/ramp" 2>/dev/null || true
  for f in "$RAMP" "$SIDEBAR"; do
    NEWEST=$(ls -1t "$f".bak.* 2>/dev/null | head -1 || true)
    if [ -n "$NEWEST" ]; then cp "$NEWEST" "$f"; echo "Restored $f from $NEWEST"; else echo "No backup for $f"; fi
  done
  echo "Reverted Phase 1. (ramp_customers table, if migrated, is harmless to leave.)"
  exit 0
fi

# Idempotency: Phase 1 marker present in ramp.ts + sidebar.
if grep -q "ramp/customer" "$RAMP" && grep -q "On/Off-ramp" "$SIDEBAR"; then
  echo "Already applied (Phase 1 endpoints + nav item present). No changes made."
  exit 0
fi

write_new() {
  local target="$1" b64="$2" marker="$3"
  mkdir -p "$(dirname "$target")"
  base64 --decode "$b64" > "$TMP/out" 2>/dev/null || { echo "ERROR: decode failed for $target." >&2; exit 1; }
  [ -s "$TMP/out" ] || { echo "ERROR: decoded $target empty." >&2; exit 1; }
  grep -q "$marker" "$TMP/out" || { echo "ERROR: decoded $target missing marker '$marker'." >&2; exit 1; }
  cp "$TMP/out" "$target"; echo "Wrote:  $target ($(wc -l < "$target") lines)"
}
edit_existing() {
  local target="$1" b64="$2" marker="$3"
  cp "$target" "$target.bak.$TS"; echo "Backup: $target.bak.$TS"
  base64 --decode "$b64" > "$TMP/out" 2>/dev/null || { echo "ERROR: decode failed for $target — left untouched." >&2; exit 1; }
  [ -s "$TMP/out" ] || { echo "ERROR: decoded $target empty — left untouched." >&2; exit 1; }
  grep -q "$marker" "$TMP/out" || { echo "ERROR: decoded $target missing marker '$marker' — left untouched." >&2; exit 1; }
  cp "$TMP/out" "$target"; echo "Wrote:  $target ($(wc -l < "$target") lines)"
}
