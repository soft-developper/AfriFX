#!/usr/bin/env bash
# ============================================================================
# fix-send-confirmation-multichain.sh
#
# WEB-ONLY, 1 EDIT: app/(app)/send/page.tsx. Fixes the send-page confirmation
# so a successful send on ANY chain shows the success message + a link to that
# chain's own explorer — not only Arc.
#
# Two Arc-only assumptions on the send page (separate from the History fix):
#   1. The success UI was gated on `isSuccess` from useWaitForTransactionReceipt
#      (wagmi) — that hook only watches the HOME (Arc) chain, so on Base/OP/etc
#      it never fired → no confirmation shown.
#   2. The success link hardcoded testnet.arcscan.app (a SECOND arcscan link,
#      separate from the History one already fixed).
#
# FIX: add a `sent` flag set from the state sendUsdc already returns (its
# per-chain /tx/find poll confirms the hash on the right chain), so success
# shows on every chain; the wagmi receipt stays as an Arc bonus. The link +
# label now come from the selected chain (selectedChain.explorer / .name),
# falling back to arcscan.
#
# NOTE: this fixes the SEND-PAGE confirmation only. Whether History rows stop
# showing "pending" depends on the settle PATCH firing (chain-agnostic, ships
# with this) AND whether the from_chain column exists for the per-chain History
# explorer link (see the separate from_chain repair + your migration check).
#
# Delivery: v2. Idempotent, backup, --revert. Verified: WEB tsc=0, next build=0
# (/send 7.8kB), byte-identical, idempotent.
#
# Usage:
#   bash fix-send-confirmation-multichain.sh           # apply
#   bash fix-send-confirmation-multichain.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_web_dir() {
  for d in "nexum-web" "afrifx-web" "." "../nexum-web" "../afrifx-web"; do
    if [ -f "$d/package.json" ] && [ -f "$d/app/(app)/send/page.tsx" ]; then (cd "$d" && pwd); return 0; fi
  done; return 1
}
WEB_DIR="$(find_web_dir || true)"
if [ -z "${WEB_DIR:-}" ]; then echo "✗ Could not find the web package." >&2; exit 1; fi
echo "• Web: $WEB_DIR"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$WEB_DIR/.fix-send-confirm-backup"
F_SEND="app/(app)/send/page.tsx"
M_SEND="isSuccess || sent"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  while IFS='|' read -r kind rel; do
    [ -z "${kind:-}" ] && continue
    bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
    [ -f "$bak" ] && { cp -f "$bak" "$WEB_DIR/$rel"; echo "  ↺ restored $rel"; } || echo "  ⚠ missing backup $rel" >&2
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."; exit 0
fi

have() { [ -f "$WEB_DIR/$1" ] && grep -qF "$2" "$WEB_DIR/$1"; }
if have "$F_SEND" "$M_SEND"; then echo "✓ Fix already applied. Nothing to do."; exit 0; fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  base64 --decode "$b64" > "$out" 2>/dev/null || { echo "✗ [$label] decode failed." >&2; exit 1; }
  [ -s "$out" ] || { echo "✗ [$label] empty." >&2; exit 1; }
  grep -qF "$marker" "$out" || { echo "✗ [$label] marker missing." >&2; exit 1; }
}
place_edit() { local o="$1" r="$2"; [ -f "$WEB_DIR/$r" ] || { echo "✗ Missing $r" >&2; exit 1; }; cp -f "$WEB_DIR/$r" "$BACKUP_DIR/${r//\//__}.$STAMP.bak"; echo "EDIT|$r" >> "$MANIFEST"; cp -f "$o" "$WEB_DIR/$r"; echo "  ~ updated $r"; }

