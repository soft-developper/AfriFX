#!/usr/bin/env bash
# ============================================================================
# ramp-phase4-part3-deposit-emails.sh
#
# Bridge.xyz on-ramp — Phase 4, PART 3 (API ONLY). Branded deposit emails.
# The LAST Phase 4 item. Builds on Phase 3 (webhooks).
#
# When a deposit reaches a terminal state, Nexum emails the user using the
# existing Resend pipeline + branded template system (baseLayout/infoCard/
# ctaButton). Fired from the Bridge webhook, deduped so each (deposit, kind)
# emails at most once even on redelivery:
#   • payment_processed         → "✅ Your deposit landed — N USDC" (0% badge,
#                                  Basescan proof)
#   • refund / refund_in_flight → "Your deposit was returned"
#   • refund_failed             → "⚠️ Action needed" (contact support)
#
#   • services/email/templates.ts       (EDIT) — depositLandedEmail +
#       depositReturnedEmail (match existing brand system).
#   • services/bridgexyz/depositNotify.ts (NEW) — maybeSendDepositEmail():
#       maps event→kind, claims the dedup slot, resolves account email via the
#       VA's account_id, sends. Best-effort: never throws into the webhook.
#   • migrations/0021_ramp_deposit_notifications.sql (NEW) — dedup table,
#       UNIQUE(virtual_account_id, deposit_id, kind).
#   • services/bridgexyz/repository.ts   (EDIT) — getAccountContact,
#       getVirtualAccountRowById, claimDepositNotification.
#   • routes/transfers.ts                (EDIT) — call maybeSendDepositEmail
#       after the webhook mirrors a terminal event.
#
# Uses existing env RESEND_API_KEY / EMAIL_FROM / APP_URL (already set for the
# other Nexum emails). If RESEND_API_KEY is unset the mailer logs instead of
# sending (dev mode) — no crash.
#
# Delivery: v2. Idempotent, backups, --revert. Verified: API tsc=0, migration
# applies, dedup claim unit-tested (first wins / dupe blocked / different kind
# allowed), all 3 templates render (0% badge, Basescan link, reason, support
# CTA). Sandbox fires no real deposit webhooks, so live emails happen on a
# production deposit — logic is unit-tested.
#
# Usage:
#   bash ramp-phase4-part3-deposit-emails.sh           # apply
#   bash ramp-phase4-part3-deposit-emails.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_api_dir() {
  for d in "nexum-api" "afrifx-api" "." "../nexum-api" "../afrifx-api"; do
    if [ -f "$d/package.json" ] && [ -d "$d/src/services/bridgexyz" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
API_DIR="$(find_api_dir || true)"
if [ -z "${API_DIR:-}" ]; then echo "✗ Could not find the API package." >&2; exit 1; fi
echo "• API package: $API_DIR"

# Guards: Phase 3 webhook + the email system must exist.
if ! grep -qF "webhookRouter.post('/bridgexyz'" "$API_DIR/src/routes/transfers.ts"; then
  echo "✗ Phase 3 webhook not detected in transfers.ts. Apply Phase 3 Part 1 first." >&2; exit 1
fi
if [ ! -f "$API_DIR/src/services/email/templates.ts" ] || [ ! -f "$API_DIR/src/services/email/client.ts" ]; then
  echo "✗ Email system (services/email) not found — unexpected repo state." >&2; exit 1
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$API_DIR/.ramp-phase4-part3-backup"

F_TMPL="src/services/email/templates.ts"
F_NOTIFY="src/services/bridgexyz/depositNotify.ts"
F_MIG="migrations/0021_ramp_deposit_notifications.sql"
F_REPO="src/services/bridgexyz/repository.ts"
F_TR="src/routes/transfers.ts"

M_TMPL="depositLandedEmail"
M_NOTIFY="maybeSendDepositEmail"
M_MIG="ramp_deposit_notifications"
M_REPO="claimDepositNotification"
M_TR="maybeSendDepositEmail"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  echo "• Reverting run: $LATEST"
  while IFS='|' read -r kind rel; do
    [ -z "${kind:-}" ] && continue
    case "$kind" in
      EDIT) bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
            if [ -f "$bak" ]; then cp -f "$bak" "$API_DIR/$rel"; echo "  ↺ restored $rel"
            else echo "  ⚠ missing backup for $rel" >&2; fi ;;
      NEW)  if [ -f "$API_DIR/$rel" ]; then rm -f "$API_DIR/$rel"; echo "  ✗ removed new $rel"; fi ;;
    esac
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."; exit 0
fi

have() { [ -f "$API_DIR/$1" ] && grep -qF "$2" "$API_DIR/$1"; }
if have "$F_TMPL" "$M_TMPL" && have "$F_NOTIFY" "$M_NOTIFY" && have "$F_MIG" "$M_MIG" \
   && have "$F_REPO" "$M_REPO" && have "$F_TR" "$M_TR"; then
  echo "✓ Phase 4 Part 3 already applied. Nothing to do."; exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then echo "✗ [$label] decode failed." >&2; exit 1; fi
  if [ ! -s "$out" ]; then echo "✗ [$label] empty." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then echo "✗ [$label] marker missing." >&2; exit 1; fi
}
place_new() { local out="$1" rel="$2"; mkdir -p "$(dirname "$API_DIR/$rel")"; cp -f "$out" "$API_DIR/$rel"; echo "NEW|$rel" >> "$MANIFEST"; echo "  + wrote $rel (new)"; }
place_edit() { local out="$1" rel="$2"; if [ ! -f "$API_DIR/$rel" ]; then echo "✗ Missing $rel" >&2; exit 1; fi; cp -f "$API_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"; echo "EDIT|$rel" >> "$MANIFEST"; cp -f "$out" "$API_DIR/$rel"; echo "  ~ updated $rel (backup saved)"; }

echo "• Applying Phase 4 Part 3 …"

