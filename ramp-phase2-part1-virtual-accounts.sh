#!/usr/bin/env bash
# ============================================================================
# ramp-phase2-part1-virtual-accounts.sh
#
# Bridge.xyz on-ramp — Phase 2, PART 1 (API ONLY).
#
# Adds the on-ramp deposit primitives to the API, built strictly from Bridge's
# official docs (apidocs.bridge.xyz):
#   • migrations/0019_ramp_corridors_and_virtual_accounts.sql  (NEW)
#       - ramp_corridors: the 6 supported on-ramp currencies, promoted out of
#         the static array so ops can enable/disable/add without a deploy.
#         ONE ROW PER CURRENCY (usd/eur/gbp/mxn/brl/cop) — Bridge's `source`
#         takes only { currency }; ACH vs wire is the depositor's choice.
#       - ramp_virtual_accounts: one Bridge virtual account per (account,
#         currency), lazily created on first selection (mirrors ramp_customers).
#   • src/services/bridgexyz/virtualAccounts.ts                (NEW)
#       - createVirtualAccount / getVirtualAccount / listVirtualAccounts /
#         getVirtualAccountActivity(/history). Typed to the doc-confirmed
#         request+response shapes. NO simulate-deposit (that's a Bridge
#         custodial-WALLETS endpoint, not virtual accounts).
#   • src/services/bridgexyz/repository.ts                     (EDIT)
#       - corridor reads + virtual-account CRUD. ramp_customers untouched.
#   • src/services/bridgexyz/config.ts                        (EDIT)
#       - corridor model corrected to 6 currencies; DB table is runtime truth.
#   • src/routes/ramp.ts                                      (EDIT)
#       - GET /ramp/corridors now reads the DB table.
#       - POST /ramp/virtual-account          (lazy create per currency)
#       - GET  /ramp/virtual-accounts         (list this account's rails)
#       - GET  /ramp/virtual-account/:currency/activity  (deposit tracker poll)
#       All verified-gated. Destination = user's Circle wallet on Base
#       (account.walletAddress; unified EVM addressing). developer_fee_percent 0.
#
# Phase 0/1 endpoints, P2P, and Trade/Swap are untouched. No user-visible
# change yet — Part 2 (the /ramp UI) builds on this once it's confirmed live.
#
# SANDBOX NOTE: Bridge sandbox does NOT move money and fires no payments
# webhooks — virtual accounts return dummy deposit instructions and /history is
# empty/dummy. This part proves request/response SCHEMA. A real deposit ->
# delivered run is a small production test, later.
#
# Delivery: v2 (per-file quoted-heredoc base64 -> decode -> verify marker +
# non-empty -> place). Idempotent (marker-guarded), timestamped backups,
# --revert. Never writes a truncated file: any decode/verify failure aborts
# and leaves the target and its backup untouched.
#
# Usage:
#   bash ramp-phase2-part1-virtual-accounts.sh           # apply
#   bash ramp-phase2-part1-virtual-accounts.sh --revert  # restore from backups
# ============================================================================
set -euo pipefail

# --- Locate the API package (tolerant of running from repo root or elsewhere).
find_api_dir() {
  for d in "nexum-api" "afrifx-api" "." "../nexum-api" "../afrifx-api"; do
    if [ -f "$d/package.json" ] && [ -d "$d/src/services/bridgexyz" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
API_DIR="$(find_api_dir || true)"
if [ -z "${API_DIR:-}" ]; then
  echo "✗ Could not find the API package (looked for */src/services/bridgexyz)." >&2
  echo "  Run this from the repo root (~/AfriFX) or the nexum-api directory." >&2
  exit 1
fi
echo "• API package: $API_DIR"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$API_DIR/.ramp-phase2-part1-backup"
MARKER_VA="Bridge.xyz virtual-account operations (Phase 2"
MARKER_REPO="listEnabledOnrampCorridors"
MARKER_CONFIG="RUNTIME SOURCE OF TRUTH IS THE ramp_corridors"
MARKER_RAMP="virtual-account/:currency/activity"
MARKER_SQL="ramp_virtual_accounts"

# File paths (relative to API_DIR).
F_SQL="migrations/0019_ramp_corridors_and_virtual_accounts.sql"
F_VA="src/services/bridgexyz/virtualAccounts.ts"
F_REPO="src/services/bridgexyz/repository.ts"
F_CONFIG="src/services/bridgexyz/config.ts"
F_RAMP="src/routes/ramp.ts"

# ---------------------------------------------------------------------------
# --revert: restore every file we backed up in the most recent run, and remove
# any NEW files we created (they have no backup).
# ---------------------------------------------------------------------------
if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then
    echo "✗ No backup directory at $BACKUP_DIR — nothing to revert." >&2
    exit 1
  fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then
    echo "✗ No manifest found in $BACKUP_DIR — nothing to revert." >&2
    exit 1
  fi
  echo "• Reverting run: $LATEST"
  while IFS='|' read -r kind rel; do
    [ -z "${kind:-}" ] && continue
    case "$kind" in
      EDIT)
        bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
        if [ -f "$bak" ]; then
          cp -f "$bak" "$API_DIR/$rel"
          echo "  ↺ restored $rel"
        else
          echo "  ⚠ missing backup for $rel (left as-is)" >&2
        fi
        ;;
      NEW)
        if [ -f "$API_DIR/$rel" ]; then
          rm -f "$API_DIR/$rel"
          echo "  ✗ removed new file $rel"
        fi
        ;;
    esac
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."
  exit 0
fi

# ---------------------------------------------------------------------------
# Idempotency: if every marker is already present, exit cleanly.
# ---------------------------------------------------------------------------
already() { [ -f "$API_DIR/$1" ] && grep -qF "$2" "$API_DIR/$1"; }
if already "$F_VA" "$MARKER_VA" \
   && already "$F_REPO" "$MARKER_REPO" \
   && already "$F_CONFIG" "$MARKER_CONFIG" \
   && already "$F_RAMP" "$MARKER_RAMP" \
   && already "$F_SQL" "$MARKER_SQL"; then
  echo "✓ Phase 2 Part 1 already applied (all markers present). Nothing to do."
  exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"
: > "$MANIFEST"
WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

# decode_verify <b64_tmp> <out_tmp> <marker> <label>
decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then
    echo "✗ [$label] base64 decode failed — aborting, nothing written." >&2; exit 1
  fi
  if [ ! -s "$out" ]; then
    echo "✗ [$label] decoded file is empty — aborting, nothing written." >&2; exit 1
  fi
  if ! grep -qF "$marker" "$out"; then
    echo "✗ [$label] marker not found in decoded content — aborting." >&2; exit 1
  fi
}

# place_new <out_tmp> <rel>
place_new() {
  local out="$1" rel="$2"
  mkdir -p "$(dirname "$API_DIR/$rel")"
  cp -f "$out" "$API_DIR/$rel"
  echo "NEW|$rel" >> "$MANIFEST"
  echo "  + wrote $rel (new)"
}

# place_edit <out_tmp> <rel>
place_edit() {
  local out="$1" rel="$2"
  if [ ! -f "$API_DIR/$rel" ]; then
    echo "✗ Expected existing file missing: $rel — aborting." >&2; exit 1
  fi
  cp -f "$API_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"
  echo "EDIT|$rel" >> "$MANIFEST"
  cp -f "$out" "$API_DIR/$rel"
  echo "  ~ updated $rel (backup saved)"
}

