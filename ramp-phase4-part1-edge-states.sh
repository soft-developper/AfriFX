#!/usr/bin/env bash
# ============================================================================
# ramp-phase4-part1-edge-states.sh
#
# Bridge.xyz on-ramp — Phase 4, PART 1 (WEB ONLY, 1 edit). Edge-state handling
# in the deposit tracker. Builds on Phase 2/3.
#
# Today the tracker only understands the happy path (funds_received →
# payment_submitted → payment_processed) and silently stalls on anything else.
# This teaches it every real Bridge virtual-account event state, confirmed from
# the official activity API enum (funds_received, payment_submitted,
# payment_processed, in_review, refund, refund_in_flight, refund_failed,
# microdeposit, account_update, deactivation, activation):
#
#   • in_review              → an amber "Deposit under review" banner above the
#                              stepper (compliance hold, usually clears itself).
#   • refund / refund_in_flight → "Deposit returned to sender" (orange), with
#                              the refund reason if Bridge provides one.
#   • refund_failed          → "Return failed — contact support" (red).
#   • microdeposit (only)    → "Verification deposit received" info banner —
#                              sub-$1 verification, not a real on-ramp.
#   • account_update / deactivation / activation → ignored (account lifecycle,
#                              not a deposit's progress).
#   • payment_processed always wins (a cleared review still delivers).
#
# A refund is terminal (funds won't deliver) so it REPLACES the stepper rather
# than leaving it stuck. Happy path is visually unchanged.
#
#   • app/(app)/ramp/page.tsx (EDIT) — DepositTracker + TRACKER_STEPS +
#     dispositionFor() + a StatusBanner. No API change, no new state.
#
# Delivery: v2 (quoted-heredoc base64 -> decode -> verify marker -> place).
# Idempotent, backup, --revert. Verified: web tsc=0, next build=0 (/ramp
# compiles), disposition classifier unit-tested 14/14 (every edge state +
# precedence: delivery>review, refund>review, microdeposit-only vs mixed).
#
# Usage:
#   bash ramp-phase4-part1-edge-states.sh           # apply
#   bash ramp-phase4-part1-edge-states.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_web_dir() {
  for d in "nexum-web" "afrifx-web" "." "../nexum-web" "../afrifx-web"; do
    if [ -f "$d/package.json" ] && [ -f "$d/hooks/useRamp.ts" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
WEB_DIR="$(find_web_dir || true)"
if [ -z "${WEB_DIR:-}" ]; then echo "✗ Could not find the web package." >&2; exit 1; fi
echo "• Web package: $WEB_DIR"

# Guard: Phase 2 onramp UI must be present (we edit its tracker).
if ! grep -qF "function OnrampFlow" "$WEB_DIR/app/(app)/ramp/page.tsx"; then
  echo "✗ Phase 2 onramp UI not detected in ramp/page.tsx. Apply Phase 2 first." >&2
  exit 1
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$WEB_DIR/.ramp-phase4-part1-backup"
F_PAGE="app/(app)/ramp/page.tsx"
MARKER="dispositionFor"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  bak="$BACKUP_DIR/${F_PAGE//\//__}.$LATEST.bak"
  if [ -f "$bak" ]; then cp -f "$bak" "$WEB_DIR/$F_PAGE"; echo "  ↺ restored $F_PAGE"; else echo "✗ missing backup" >&2; exit 1; fi
  echo "✓ Revert complete."; exit 0
fi

if [ -f "$WEB_DIR/$F_PAGE" ] && grep -qF "$MARKER" "$WEB_DIR/$F_PAGE"; then
  echo "✓ Phase 4 Part 1 already applied. Nothing to do."; exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

echo "• Applying Phase 4 Part 1 …"

