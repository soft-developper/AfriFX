#!/usr/bin/env bash
# ============================================================================
# fix-multichain-send-history.sh
#
# Multichain-send cleanup (API + WEB). When Send became multichain, two things
# stayed Arc-only and broke for sends on Base/OP/Arbitrum/etc:
#
#   1. SETTLEMENT — the settle PATCH only ran on Arc (`if publicClient &&
#      isHome`), and the on-chain settler is an Arc-only Memo-event listener.
#      So a successful send on any other chain never got marked settled →
#      stuck "pending" forever in History, no success/confirmation shown.
#   2. EXPLORER LINK — History hardcoded testnet.arcscan.app for every send,
#      so a Base tx linked to Arc's explorer (dead link), and the record
#      didn't even store which chain it was.
#
# FIX (going-forward; existing pending rows are left as-is by choice):
#   • migrations/0022_transactions_from_chain.sql (NEW) — add nullable
#     from_chain to transactions (NULL = Arc, so legacy rows are unaffected).
#   • src/routes/transactions.ts (EDIT, API) — accept + store fromChain on
#     POST (GET already SELECT *, so it returns automatically).
#   • app/(app)/send/page.tsx (EDIT, WEB) — send fromChain: chainKey; settle
#     the record on EVERY chain from the state sendUsdc already returned (its
#     /tx/find poll confirmed the right chain), not just Arc. Arc still also
#     waits on the wagmi receipt for a definitive success/failure.
#   • app/(app)/history/page.tsx (EDIT, WEB) — build the send explorer URL
#     from the record's from_chain via cctp-chains (per-chain explorer),
#     falling back to Arc for legacy rows.
#
# Bridge rows, P2P, corridors, ramp: untouched. No behaviour change on Arc.
#
# Delivery: v2 (quoted-heredoc base64 -> decode -> verify marker -> place).
# Idempotent, backups, --revert. Verified: API tsc=0, WEB tsc=0, next build=0
# (/history + /send compile), migration applies + from_chain stores + settle
# flips to settled + legacy NULL insert still works.
#
# Usage:
#   bash fix-multichain-send-history.sh           # apply
#   bash fix-multichain-send-history.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_api_dir() {
  for d in "nexum-api" "afrifx-api" "." "../nexum-api" "../afrifx-api"; do
    if [ -f "$d/package.json" ] && [ -f "$d/src/routes/transactions.ts" ]; then (cd "$d" && pwd); return 0; fi
  done; return 1
}
find_web_dir() {
  for d in "nexum-web" "afrifx-web" "." "../nexum-web" "../afrifx-web"; do
    if [ -f "$d/package.json" ] && [ -f "$d/app/(app)/history/page.tsx" ]; then (cd "$d" && pwd); return 0; fi
  done; return 1
}
API_DIR="$(find_api_dir || true)"; WEB_DIR="$(find_web_dir || true)"
if [ -z "${API_DIR:-}" ]; then echo "✗ Could not find the API package." >&2; exit 1; fi
if [ -z "${WEB_DIR:-}" ]; then echo "✗ Could not find the web package." >&2; exit 1; fi
echo "• API: $API_DIR"
echo "• Web: $WEB_DIR"

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$API_DIR/.fix-multichain-send-backup"   # single manifest dir under API

F_MIG="migrations/0022_transactions_from_chain.sql"
F_TR="src/routes/transactions.ts"
F_SEND="app/(app)/send/page.tsx"
F_HIST="app/(app)/history/page.tsx"

M_MIG="from_chain"
M_TR="from_chain"
M_SEND="fromChain: chainKey"
M_HIST="sendExplorer"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  echo "• Reverting run: $LATEST"
  while IFS='|' read -r kind pkg rel; do
    [ -z "${kind:-}" ] && continue
    base="$API_DIR"; [ "$pkg" = "WEB" ] && base="$WEB_DIR"
    case "$kind" in
      EDIT) bak="$BACKUP_DIR/${pkg}__${rel//\//__}.$LATEST.bak"
            if [ -f "$bak" ]; then cp -f "$bak" "$base/$rel"; echo "  ↺ restored $pkg/$rel"; else echo "  ⚠ missing backup $pkg/$rel" >&2; fi ;;
      NEW)  if [ -f "$base/$rel" ]; then rm -f "$base/$rel"; echo "  ✗ removed new $pkg/$rel"; fi ;;
    esac
  done < "$BACKUP_DIR/manifest-$LATEST.txt"
  echo "✓ Revert complete."; exit 0
fi

haveA() { [ -f "$API_DIR/$1" ] && grep -qF "$2" "$API_DIR/$1"; }
haveW() { [ -f "$WEB_DIR/$1" ] && grep -qF "$2" "$WEB_DIR/$1"; }
if haveA "$F_MIG" "$M_MIG" && haveA "$F_TR" "$M_TR" && haveW "$F_SEND" "$M_SEND" && haveW "$F_HIST" "$M_HIST"; then
  echo "✓ Fix already applied. Nothing to do."; exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then echo "✗ [$label] decode failed." >&2; exit 1; fi
  if [ ! -s "$out" ]; then echo "✗ [$label] empty." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then echo "✗ [$label] marker missing." >&2; exit 1; fi
}
place_new_api()  { local o="$1" r="$2"; mkdir -p "$(dirname "$API_DIR/$r")"; cp -f "$o" "$API_DIR/$r"; echo "NEW|API|$r" >> "$MANIFEST"; echo "  + wrote API/$r (new)"; }
place_edit_api() { local o="$1" r="$2"; [ -f "$API_DIR/$r" ] || { echo "✗ Missing $r" >&2; exit 1; }; cp -f "$API_DIR/$r" "$BACKUP_DIR/API__${r//\//__}.$STAMP.bak"; echo "EDIT|API|$r" >> "$MANIFEST"; cp -f "$o" "$API_DIR/$r"; echo "  ~ updated API/$r"; }
place_edit_web() { local o="$1" r="$2"; [ -f "$WEB_DIR/$r" ] || { echo "✗ Missing $r" >&2; exit 1; }; cp -f "$WEB_DIR/$r" "$BACKUP_DIR/WEB__${r//\//__}.$STAMP.bak"; echo "EDIT|WEB|$r" >> "$MANIFEST"; cp -f "$o" "$WEB_DIR/$r"; echo "  ~ updated WEB/$r"; }

echo "• Applying multichain-send fix …"

