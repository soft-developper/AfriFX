#!/usr/bin/env bash
# ============================================================================
# ramp-phase4-part2-fee-breakdown.sh
#
# Bridge.xyz on-ramp — Phase 4, PART 2 (WEB ONLY, 2 edits). A live sent → fees
# → received breakdown in the deposit tracker. Builds on Phase 4 Part 1.
#
# Shows the user exactly what happens to their money, filling in as the deposit
# progresses:
#   • You send      — source fiat amount (from funds_received, pre-fee)
#   • Fees          — developer + exchange fee, ALWAYS with a "0% at launch"
#                     badge shown explicitly (even at zero) as a trust signal
#   • Network fee   — gas, only if non-zero
#   • You receive   — final USDC delivered (from payment_processed.amount, or
#                     receipt.final_amount), "Pending…" until delivered
#
# Amount semantics are per Bridge's docs (confirmed): payment_processed.amount
# is the DESTINATION (USDC delivered); other events' amount is the SOURCE fiat.
# The breakdown only renders on the normal (non-returned, non-microdeposit)
# path, right under the stepper.
#
#   • hooks/useRamp.ts        (EDIT) — RampActivityEvent gains the fee fields
#     (developer_fee_amount, exchange_fee_amount, subtotal_amount, gas_fee,
#     receipt.*). Type-only; no behaviour change.
#   • app/(app)/ramp/page.tsx (EDIT) — DepositBreakdown + Row + fmt helpers,
#     rendered inside DepositTracker.
#
# Delivery: v2. Idempotent, backups, --revert. Verified: web tsc=0, next
# build=0 (/ramp 12.6kB), breakdown math unit-tested 8/8 (source vs destination
# amount selection, fee summing, receipt.final_amount fallback, pending states).
#
# Usage:
#   bash ramp-phase4-part2-fee-breakdown.sh           # apply
#   bash ramp-phase4-part2-fee-breakdown.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_web_dir() {
  for d in "nexum-web" "afrifx-web" "." "../nexum-web" "../afrifx-web"; do
    if [ -f "$d/package.json" ] && [ -f "$d/hooks/useRamp.ts" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
WEB_DIR="$(find_web_dir || true)"
if [ -z "${WEB_DIR:-}" ]; then echo "✗ Could not find the web package." >&2; exit 1; fi
echo "• Web package: $WEB_DIR"

# Guard: Phase 4 Part 1 must be present (we render inside its tracker).
if ! grep -qF "dispositionFor" "$WEB_DIR/app/(app)/ramp/page.tsx"; then
  echo "✗ Phase 4 Part 1 (edge states) not detected. Apply it first." >&2; exit 1
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$WEB_DIR/.ramp-phase4-part2-backup"
MARKER_HOOK="developer_fee_amount"
MARKER_PAGE="DepositBreakdown"
F_HOOK="hooks/useRamp.ts"
F_PAGE="app/(app)/ramp/page.tsx"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  for rel in "$F_HOOK" "$F_PAGE"; do
    bak="$BACKUP_DIR/${rel//\//__}.$LATEST.bak"
    if [ -f "$bak" ]; then cp -f "$bak" "$WEB_DIR/$rel"; echo "  ↺ restored $rel"; else echo "  ⚠ missing backup $rel" >&2; fi
  done
  echo "✓ Revert complete."; exit 0
fi

have() { [ -f "$WEB_DIR/$1" ] && grep -qF "$2" "$WEB_DIR/$1"; }
if have "$F_HOOK" "$MARKER_HOOK" && have "$F_PAGE" "$MARKER_PAGE"; then
  echo "✓ Phase 4 Part 2 already applied. Nothing to do."; exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then echo "✗ [$label] decode failed." >&2; exit 1; fi
  if [ ! -s "$out" ]; then echo "✗ [$label] empty." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then echo "✗ [$label] marker missing." >&2; exit 1; fi
}
place_edit() {
  local out="$1" rel="$2"
  if [ ! -f "$WEB_DIR/$rel" ]; then echo "✗ Missing $rel" >&2; exit 1; fi
  cp -f "$WEB_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"
  echo "EDIT|$rel" >> "$MANIFEST"
  cp -f "$out" "$WEB_DIR/$rel"
  echo "  ~ updated $rel (backup saved)"
}

