#!/usr/bin/env bash
# ramp-phase0-bridge-skeleton.sh
# Phase 0 of the Bridge.xyz fiat on/off-ramp: a self-contained skeleton on
# BRIDGE's OWN structure (NOT wired through the Flutterwave-style
# FiatRampProvider interface). API-only, purely additive, NO user-visible
# change, NO DB, NO money movement.
#
#   NEW  nexum-api/src/services/bridgexyz/client.ts   (config gate + typed fetch + read-only ping)
#   NEW  nexum-api/src/services/bridgexyz/config.ts   (Base landing chain + corridor data)
#   NEW  nexum-api/src/routes/ramp.ts                 (GET /ramp/health, GET /ramp/corridors)
#   EDIT nexum-api/src/index.ts                       (import + mount /ramp + boot log)
#
# Inert unless BRIDGE_API_KEY is set. After deploy: GET /ramp/health verifies
# the sandbox key from Render. v2 delivery (per-file quoted heredoc + decode-
# verify-before-replace). Idempotent, --revert, timestamped backup for index.ts.
set -euo pipefail

if [ -d "nexum-api" ]; then ROOT="."
elif [ -d "../nexum-api" ]; then ROOT=".."
else echo "ERROR: run from repo root (~/AfriFX) so nexum-api is visible." >&2; exit 1; fi

API="$ROOT/nexum-api"
SVC_DIR="$API/src/services/bridgexyz"
CLIENT="$SVC_DIR/client.ts"
CONFIG="$SVC_DIR/config.ts"
RAMP="$API/src/routes/ramp.ts"
INDEX="$API/src/index.ts"

[ -f "$INDEX" ] || { echo "ERROR: $INDEX not found." >&2; exit 1; }

TS=$(date +%Y%m%d-%H%M%S)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- revert: delete the 3 new files + restore index.ts from newest backup ---
if [ "${1:-}" = "--revert" ]; then
  rm -f "$CLIENT" "$CONFIG" "$RAMP"
  rmdir "$SVC_DIR" 2>/dev/null || true
  NEWEST=$(ls -1t "$INDEX".bak.* 2>/dev/null | head -1 || true)
  if [ -n "$NEWEST" ]; then cp "$NEWEST" "$INDEX"; echo "Restored $INDEX from $NEWEST"; else echo "No index.ts backup found"; fi
  echo "Reverted Phase 0 (removed bridgexyz service + ramp route)."
  exit 0
fi

# --- idempotency ---
if [ -f "$CLIENT" ] && grep -q "rampRouter" "$INDEX"; then
  echo "Already applied (bridgexyz client + rampRouter present). No changes made."
  exit 0
fi

mkdir -p "$SVC_DIR"

# write_new <target> <b64file> <marker>
write_new() {
  local target="$1" b64="$2" marker="$3"
  if ! base64 --decode "$b64" > "$TMP/out" 2>/dev/null; then
    echo "ERROR: base64 decode failed for $target." >&2; exit 1; fi
  if [ ! -s "$TMP/out" ]; then echo "ERROR: decoded $target empty." >&2; exit 1; fi
  if ! grep -q "$marker" "$TMP/out"; then
    echo "ERROR: decoded $target missing marker '$marker'." >&2; exit 1; fi
  cp "$TMP/out" "$target"
  echo "Wrote:  $target ($(wc -l < "$target") lines)"
}

# edit_existing <target> <b64file> <marker>  (backs up first)
edit_existing() {
  local target="$1" b64="$2" marker="$3"
  cp "$target" "$target.bak.$TS"; echo "Backup: $target.bak.$TS"
  if ! base64 --decode "$b64" > "$TMP/out" 2>/dev/null; then
    echo "ERROR: base64 decode failed for $target — left untouched." >&2; exit 1; fi
  if [ ! -s "$TMP/out" ]; then echo "ERROR: decoded $target empty — left untouched." >&2; exit 1; fi
  if ! grep -q "$marker" "$TMP/out"; then
    echo "ERROR: decoded $target missing marker '$marker' — left untouched." >&2; exit 1; fi
  cp "$TMP/out" "$target"
  echo "Wrote:  $target ($(wc -l < "$target") lines)"
}
