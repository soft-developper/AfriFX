#!/usr/bin/env bash
#
# 17-all-chain-usdc-total.sh
# -------------------------------------------------------------------
# Adds a cross-chain "Total USDC · All chains" figure to BOTH the
# Dashboard and the Wallet nav, positioned FIRST — ahead of the existing
# Arc-only USDC display — and relabels the existing figures so the two
# read distinctly.
#
# It reuses the hook you already have, useAllChainUsdcBalances (the same
# one the Wallet's per-chain cards use), and SUMS it. That hook maps over
# cctpChains() with 6-decimal USDC conversion, and its Arc entry reads the
# same address (0x3600...) at the same 6 decimals as useUSDCBalance — so
# the total already includes Arc and matches the Arc figure exactly. No
# double-count, no 18-vs-6 decimal mismatch.
#
# Dashboard (app/(app)/dashboard/page.tsx):
#   - NEW first stat card "Total USDC · All chains" (highlighted),
#     sub "across N supported chains"
#   - existing Arc card relabelled "USDC · Arc" (sub "on Arc Testnet")
#   - stat grid lg:grid-cols-4 -> lg:grid-cols-3 so 5 cards flow 3+2
#     with no orphaned card (the highlighted Total anchors top-left)
#
# Wallet (app/(app)/wallet/WalletContent.tsx):
#   - portfolio card now LEADS with the all-chain USDC total; the total
#     portfolio value (incl. escrow) moves to the caption beneath it
#   - fixes two stale "on Arc Testnet" labels that predated multi-chain
#     balances (header subtitle + portfolio caption)
#
# Both files typecheck clean (npx tsc --noEmit: 0 errors, full repo).
# base64 whole-file rewrite, byte-identical verified. Backup + --revert.
# Idempotent. Web-only deploy.
# -------------------------------------------------------------------
set -euo pipefail

if   [ -f "./tailwind.config.ts" ] && [ -d "./app" ]; then WEB="."
elif [ -d "./nexum-web" ];                             then WEB="./nexum-web"
elif [ -d "./Nexum-main/nexum-web" ];                  then WEB="./Nexum-main/nexum-web"
else echo "ERROR: run from nexum-web or its parent (couldn't find tailwind.config.ts)." >&2; exit 1; fi
cd "$WEB"
echo "==> Working in: $(pwd)"

BACKUP=".fix17-backup"
FILES=("app/(app)/dashboard/page.tsx" "app/(app)/wallet/WalletContent.tsx")

if [ "${1:-}" = "--revert" ]; then
  latest=$(ls -1dt "$BACKUP"/* 2>/dev/null | head -n1 || true)
  [ -z "$latest" ] && { echo "No backup found."; exit 1; }
  echo "==> Reverting from $latest"
  for f in "${FILES[@]}"; do [ -f "$latest/$f" ] && mkdir -p "$(dirname "$f")" && cp "$latest/$f" "$f" && echo "   restored $f"; done
  echo "==> Revert complete."; exit 0
fi

STAMP=$(date +%Y%m%d-%H%M%S); DEST="$BACKUP/$STAMP"; mkdir -p "$DEST"
for f in "${FILES[@]}"; do [ -f "$f" ] && { mkdir -p "$DEST/$(dirname "$f")"; cp "$f" "$DEST/$f"; }; done
echo "==> Backup written to $DEST"

write_file() { local dest="$1"; mkdir -p "$(dirname "$dest")"; base64 -d > "$dest"; echo "   wrote $dest"; }

