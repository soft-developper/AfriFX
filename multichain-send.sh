# multichain-send.sh  (v2 — robust delivery)
# Lets Send move USDC out of the user's Circle wallet on ANY supported chain,
# not just Arc. A send is now a plain same-chain token transfer of the native
# USDC on the chosen chain (no Gateway burn/mint). If the user has no USDC on
# that chain, the UI points them at the CCTP bridge.
#
# 3 files, cross-package (web + api):
#   api  nexum-api/src/routes/auth.ts
#   web  nexum-web/hooks/useCircleTx.ts
#   web  nexum-web/app/(app)/send/page.tsx
#
# Delivery: each file's base64 payload is written to a temp file via a QUOTED
# heredoc (no shell expansion, no mega-line), decoded, and VERIFIED non-empty
# before it replaces the target. A decode failure restores the backup and
# aborts — it can never leave a truncated file. Idempotent, --revert, backups.
set -euo pipefail

if [ -d "nexum-api" ] && [ -d "nexum-web" ]; then ROOT="."
elif [ -d "../nexum-api" ] && [ -d "../nexum-web" ]; then ROOT=".."
else echo "ERROR: run from repo root (~/AfriFX)." >&2; exit 1; fi

AUTH="$ROOT/nexum-api/src/routes/auth.ts"
HOOK="$ROOT/nexum-web/hooks/useCircleTx.ts"
SEND="$ROOT/nexum-web/app/(app)/send/page.tsx"
for f in "$AUTH" "$HOOK" "$SEND"; do
  [ -f "$f" ] || { echo "ERROR: target not found: $f" >&2; exit 1; }
done

TS=$(date +%Y%m%d-%H%M%S)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# --- revert: restore newest backup of each file ---
if [ "${1:-}" = "--revert" ]; then
  for f in "$AUTH" "$HOOK" "$SEND"; do
    NEWEST=$(ls -1t "$f".bak.* 2>/dev/null | head -1 || true)
    if [ -n "$NEWEST" ]; then cp "$NEWEST" "$f"; echo "Reverted $f from $NEWEST"; else echo "No backup for $f"; fi
  done
  exit 0
fi

# --- idempotency ---
if grep -q "resolveTransferWallet" "$AUTH"; then
  echo "Already applied (resolveTransferWallet present in auth.ts). No changes made."
  exit 0
fi

# apply <target> <b64file> <marker>
apply() {
  local target="$1" b64="$2" marker="$3"
  local backup="$target.bak.$TS"
  cp "$target" "$backup"
  echo "Backup: $backup"
  # Decode to a temp file first; only overwrite the target if it looks sane.
  if ! base64 --decode "$b64" > "$TMP/out" 2>/dev/null; then
    echo "ERROR: base64 decode failed for $target — target left untouched." >&2
    exit 1
  fi
  if [ ! -s "$TMP/out" ]; then
    echo "ERROR: decoded payload for $target is empty — target left untouched." >&2
    exit 1
  fi
  if ! grep -q "$marker" "$TMP/out"; then
    echo "ERROR: decoded $target missing expected marker '$marker' — target left untouched." >&2
    exit 1
  fi
  cp "$TMP/out" "$target"
  echo "Wrote:  $target ($(wc -l < "$target") lines)"
}
