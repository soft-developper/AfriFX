LIQ_MARKER="getLiquidationAddressDrains"
MIG_MARKER="ramp_liquidation_addresses"

# ---- revert -----------------------------------------------------------------
if [ "${1:-}" = "--revert" ]; then
  echo "Reverting Phase 5 Part 1..."
  # New files: remove them.
  for f in "$EXT" "$LIQ" "$MIG"; do
    if [ -f "$f" ]; then rm -f "$f"; echo "  removed $f"; fi
  done
  # repository.ts: restore newest backup if present.
  BK="$(ls -t "$REPO".bak.* 2>/dev/null | head -1 || true)"
  if [ -n "$BK" ]; then cp "$BK" "$REPO"; echo "  restored $REPO from $BK"; else
    # Fallback: strip the appended block from its marker banner to EOF.
    if grep -q "Phase 5 — off-ramp: external accounts" "$REPO" 2>/dev/null; then
      LINE="$(grep -n "// ══════════════════════════════════════════════════════════" "$REPO" | tail -2 | head -1 | cut -d: -f1)"
      : # (backup restore is the primary path; this is a guard only)
    fi
    echo "  no repository.ts backup found — left as-is"
  fi
  echo "Revert complete. Re-run per-package: cd $API && npx tsc --noEmit && npm run build"
  exit 0
fi

# ---- helper: decode a base64 heredoc temp file → verify → place -------------
# Args: <target_path> <b64_tmp> <marker> <is_new:0|1>
place_file () {
  local target="$1" b64tmp="$2" marker="$3" isnew="$4"
  local decoded="${b64tmp%.b64}.decoded"
  if ! base64 --decode "$b64tmp" > "$decoded" 2>/dev/null; then
    echo "ERROR: base64 decode failed for $target — aborting, target untouched." >&2; exit 1; fi
  if [ ! -s "$decoded" ]; then
    echo "ERROR: decoded file for $target is empty — aborting, target untouched." >&2; exit 1; fi
  if ! grep -q "$marker" "$decoded"; then
    echo "ERROR: marker '$marker' missing from decoded $target — aborting." >&2; exit 1; fi
  if [ "$isnew" = "1" ]; then
    mkdir -p "$(dirname "$target")"
    cp "$decoded" "$target"
  else
    cp "$target" "$target.bak.$STAMP"
    cp "$decoded" "$target"
  fi
  echo "  wrote $target ($(wc -l < "$target") lines)"
}

