# v2 delivery: each file's base64 written to its own quoted-heredoc temp file,
# decoded, verified (decode-ok + non-empty + marker present) BEFORE replacing
# the target. Idempotent (marker guards). --revert restores timestamped backups.
#
# Usage:
#   bash ramp-phase5-part1-offramp-services.sh          # apply
#   bash ramp-phase5-part1-offramp-services.sh --revert # undo
# ============================================================
set -euo pipefail

STAMP="$(date +%Y%m%d-%H%M%S)"

# Resolve the api package whether run from repo root or from nexum-api.
if [ -d "nexum-api" ]; then API="nexum-api"
elif [ -d "../nexum-api" ]; then API="../nexum-api"
elif [ -f "package.json" ] && grep -q '"name": *"nexum-api"\|afrifx-api' package.json 2>/dev/null; then API="."
else echo "ERROR: run from the repo root (~/AfriFX) or nexum-api." >&2; exit 1; fi
echo "Using API package at: $API"

REPO="$API/src/services/bridgexyz/repository.ts"
EXT="$API/src/services/bridgexyz/externalAccounts.ts"
LIQ="$API/src/services/bridgexyz/liquidationAddresses.ts"
MIG="$API/migrations/0024_ramp_offramp.sql"

REPO_MARKER="listEnabledOfframpCorridors"
