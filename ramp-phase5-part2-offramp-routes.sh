# ============================================================
# ramp-phase5-part2-offramp-routes.sh
#
# Phase 5 (OFF-RAMP) — Part 2: API routes.
# API-ONLY. Depends on Part 1 (offramp service layer + DB + repository CRUD).
#
# Adds to nexum-api/src/routes/ramp.ts (single-file EDIT):
#   GET  /ramp/offramp/corridors                         enabled off-ramp corridors
#   GET  /ramp/external-account                          list registered bank accounts
#   POST /ramp/external-account                          register bank account (currency-branched)
#   GET  /ramp/liquidation-address                       list off-ramp addresses
#   POST /ramp/liquidation-address                       lazily create off-ramp address
#   GET  /ramp/liquidation-address/:currency/drains      drain-history status poll
#
# All routes require a verified Bridge customer + an enabled off-ramp corridor.
# return_address on every liquidation address = the user's own Circle wallet.
# Built from Bridge's official liquidation-address docs.
#
# v2 delivery: base64 payload -> own temp file -> decode -> verify
# (decode-ok + non-empty + marker present) BEFORE replacing the target. The
# whole new ramp.ts is shipped (not a patch), so there is no partial-apply risk.
# Idempotent (marker guard). --revert restores the timestamped backup.
#
# ⚠ PREREQUISITE: run Part 1 first. This script checks for the Part 1 service
# functions and aborts cleanly if they're missing (ramp.ts wouldn't compile).
#
# Usage:
#   bash ramp-phase5-part2-offramp-routes.sh          # apply
#   bash ramp-phase5-part2-offramp-routes.sh --revert # undo
# ============================================================
set -euo pipefail

STAMP="$(date +%Y%m%d-%H%M%S)"

if [ -d "nexum-api" ]; then API="nexum-api"
elif [ -d "../nexum-api" ]; then API="../nexum-api"
