RAMP="$API/src/routes/ramp.ts"
EXT_SVC="$API/src/services/bridgexyz/externalAccounts.ts"
LIQ_SVC="$API/src/services/bridgexyz/liquidationAddresses.ts"
MARKER="router.post('/liquidation-address'"

if [ ! -f "$RAMP" ]; then echo "ERROR: $RAMP not found." >&2; exit 1; fi

# ---- revert -----------------------------------------------------------------
if [ "${1:-}" = "--revert" ]; then
  echo "Reverting Phase 5 Part 2..."
  BK="$(ls -t "$RAMP".bak.* 2>/dev/null | head -1 || true)"
  if [ -n "$BK" ]; then cp "$BK" "$RAMP"; echo "  restored $RAMP from $BK"
  else echo "  no ramp.ts backup found — left as-is"; fi
  echo "Revert complete. Re-run: cd $API && npx tsc --noEmit && npm run build"
  exit 0
fi

# ---- prerequisite check: Part 1 must be applied -----------------------------
if [ ! -f "$EXT_SVC" ] || ! grep -q "OFFRAMP_RAILS" "$EXT_SVC" 2>/dev/null \
   || [ ! -f "$LIQ_SVC" ] || ! grep -q "getLiquidationAddressDrains" "$LIQ_SVC" 2>/dev/null \
   || ! grep -q "listEnabledOfframpCorridors" "$API/src/services/bridgexyz/repository.ts" 2>/dev/null; then
  echo "ERROR: Part 1 not detected (missing offramp services / repository CRUD)." >&2
  echo "       Run ramp-phase5-part1-offramp-services.sh first." >&2
