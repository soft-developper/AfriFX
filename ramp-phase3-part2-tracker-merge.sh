#!/usr/bin/env bash
# ============================================================================
# ramp-phase3-part2-tracker-merge.sh
#
# Bridge.xyz on-ramp — Phase 3, PART 2 (API ONLY, 1 edit). Builds on Part 1.
#
# Wires the webhook mirror into the deposit tracker. The activity endpoint
# GET /ramp/virtual-account/:currency/activity now MERGES two sources:
#   • Bridge's /history poll  — GROUND TRUTH, always authoritative.
#   • ramp_deposit_events     — the webhook mirror (Part 1), which can be
#     fresher than the next 15s poll, so the stepper advances the instant a
#     webhook lands.
# Union is by (deposit_id, event_type): poll events win, mirror-only events are
# added. It also RECONCILES the other way — poll events the mirror is missing
# are written back (source 'poll'), so a webhook that never arrived leaves no
# gap. If Bridge's /history call fails, the mirror is still returned (graceful
# degradation) instead of erroring.
#
#   • src/routes/ramp.ts (EDIT) — the activity route + 2 repository imports.
#
# The /ramp web tracker needs NO change: it already reads events[].type, which
# the merged response still provides — it just gets fresher data. No new env,
# no migration (Part 1's tables are reused), no user-visible layout change.
#
# NOTE: with sandbox firing no real VA webhooks, the mirror stays empty there,
# so the merged endpoint behaves exactly like the old poll-only one until a real
# (production) deposit populates it — i.e. this is safe to ship now and simply
# "lights up" when real webhooks flow.
#
# Delivery: v2 (quoted-heredoc base64 -> decode -> verify marker -> place).
# Idempotent, backups, --revert. Verified: API tsc=0, merge/union logic unit-
# tested (dedupe + fresher-event add + reconcile), byte-identical, idempotent.
#
# Usage:
#   bash ramp-phase3-part2-tracker-merge.sh           # apply
#   bash ramp-phase3-part2-tracker-merge.sh --revert  # restore
# ============================================================================
set -euo pipefail

find_api_dir() {
  for d in "nexum-api" "afrifx-api" "." "../nexum-api" "../afrifx-api"; do
    if [ -f "$d/package.json" ] && [ -d "$d/src/services/bridgexyz" ]; then
      (cd "$d" && pwd); return 0
    fi
  done
  return 1
}
API_DIR="$(find_api_dir || true)"
if [ -z "${API_DIR:-}" ]; then
  echo "✗ Could not find the API package." >&2; exit 1
fi
echo "• API package: $API_DIR"

# Guard: Part 1 must be present (we use its mirror table + repo fns).
if ! grep -qF "recordWebhookEvent" "$API_DIR/src/services/bridgexyz/repository.ts"; then
  echo "✗ Phase 3 Part 1 not detected (recordWebhookEvent missing). Apply Part 1 first." >&2
  exit 1
fi

STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$API_DIR/.ramp-phase3-part2-backup"
MARKER="MERGES two sources"
F_RAMP="src/routes/ramp.ts"

if [ "${1:-}" = "--revert" ]; then
  if [ ! -d "$BACKUP_DIR" ]; then echo "✗ No backups." >&2; exit 1; fi
  LATEST="$(ls -1 "$BACKUP_DIR" | sed -n 's/^manifest-\(.*\)\.txt$/\1/p' | sort | tail -1 || true)"
  if [ -z "${LATEST:-}" ]; then echo "✗ No manifest." >&2; exit 1; fi
  bak="$BACKUP_DIR/${F_RAMP//\//__}.$LATEST.bak"
  if [ -f "$bak" ]; then cp -f "$bak" "$API_DIR/$F_RAMP"; echo "  ↺ restored $F_RAMP"; else echo "✗ missing backup" >&2; exit 1; fi
  echo "✓ Revert complete."; exit 0
fi

if [ -f "$API_DIR/$F_RAMP" ] && grep -qF "$MARKER" "$API_DIR/$F_RAMP"; then
  echo "✓ Phase 3 Part 2 already applied. Nothing to do."; exit 0
fi

mkdir -p "$BACKUP_DIR"
MANIFEST="$BACKUP_DIR/manifest-$STAMP.txt"; : > "$MANIFEST"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT

decode_verify() {
  local b64="$1" out="$2" marker="$3" label="$4"
  if ! base64 --decode "$b64" > "$out" 2>/dev/null; then echo "✗ [$label] decode failed." >&2; exit 1; fi
  if [ ! -s "$out" ]; then echo "✗ [$label] empty." >&2; exit 1; fi
  if ! grep -qF "$marker" "$out"; then echo "✗ [$label] marker missing." >&2; exit 1; fi
}
place_edit() {
  local out="$1" rel="$2"
  if [ ! -f "$API_DIR/$rel" ]; then echo "✗ Missing $rel" >&2; exit 1; fi
  cp -f "$API_DIR/$rel" "$BACKUP_DIR/${rel//\//__}.$STAMP.bak"
  echo "EDIT|$rel" >> "$MANIFEST"
  cp -f "$out" "$API_DIR/$rel"
  echo "  ~ updated $rel (backup saved)"
}

